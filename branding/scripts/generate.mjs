// Generates branding/generated from branding/source.
// Run locally only when a source logo changes; the output is committed.
//
//   npm i --no-save @resvg/resvg-js@2.6.2   (any folder; pass it with NODE_PATH if needed)
//   node branding/scripts/generate.mjs
//   python branding/scripts/make-ico.py
//
// branding/apply.mjs (run during the Docker build) only copies the files produced here.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { Resvg } = require('@resvg/resvg-js');

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = (f) => readFileSync(join(root, 'source', f), 'utf8');
const out = join(root, 'generated');
const pub = join(out, 'webapp-public');
mkdirSync(pub, { recursive: true });

// ---- Icon geometry, extracted from the source icon ----
const iconSvg = src('r16-sync-icon.svg');
const viewBox = iconSvg.match(/viewBox="([^"]+)"/)[1];
const [, , vbW, vbH] = viewBox.split(/\s+/).map(Number);
const pathD = iconSvg.match(/<path[^>]*\sd="([^"]+)"/)[1];

const iconWithFill = (fill) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"><path fill="${fill}" d="${pathD}"/></svg>\n`;

// Icon centred inside a filled circle (replaces Nango's circled marks).
const circled = (bg, fg, scale = 0.58) => {
    const size = 1000;
    const s = (size * scale) / Math.max(vbW, vbH);
    const tx = (size - vbW * s) / 2;
    const ty = (size - vbH * s) / 2;
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}"><circle cx="${size / 2}" cy="${size / 2}" r="${size / 2}" fill="${bg}"/><g transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)}) scale(${s.toFixed(6)})"><path fill="${fg}" d="${pathD}"/></g></svg>\n`;
};

// Icon on a solid square, for platforms that do not support transparency (iOS, PWA).
const squared = (bg, fg, scale = 0.7) => {
    const size = 1000;
    const s = (size * scale) / Math.max(vbW, vbH);
    const tx = (size - vbW * s) / 2;
    const ty = (size - vbH * s) / 2;
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" fill="${bg}"/><g transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)}) scale(${s.toFixed(6)})"><path fill="${fg}" d="${pathD}"/></g></svg>\n`;
};

// Square canvas with the icon centred and transparent background (favicons).
const padded = (fg) => {
    const size = 1000;
    const s = (size * 0.96) / Math.max(vbW, vbH);
    const tx = (size - vbW * s) / 2;
    const ty = (size - vbH * s) / 2;
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}"><g transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)}) scale(${s.toFixed(6)})"><path fill="${fg}" d="${pathD}"/></g></svg>\n`;
};

const png = (svg, width, file) => {
    const data = new Resvg(svg, { fitTo: { mode: 'width', value: width } }).render().asPng();
    writeFileSync(join(pub, file), data);
};

// ---- SVGs that replace packages/webapp/public/logo-*.svg ----
const white = iconWithFill('#ffffff');
writeFileSync(join(pub, 'logo-dark.svg'), white); // white mark for dark backgrounds
writeFileSync(join(pub, 'logo-circled.svg'), circled('#000000', '#ffffff'));
writeFileSync(join(pub, 'logo-light.svg'), circled('#000000', '#ffffff'));
writeFileSync(join(pub, 'logo-icon-dark.svg'), circled('#000000', '#ffffff'));
writeFileSync(join(pub, 'logo-icon-light.svg'), circled('#ffffff', '#000000'));
writeFileSync(join(pub, 'logo-text.svg'), src('r16-sync-logo-white.svg'));
writeFileSync(join(pub, 'logo-dark-background-vertical.svg'), src('r16-sync-logo-white.svg'));

// ---- Raster icons that replace packages/webapp/public/*.png ----
png(padded('#000000'), 16, 'favicon-16x16.png');
png(padded('#000000'), 32, 'favicon-32x32.png');
png(padded('#ffffff'), 16, 'favicon-dark-16x16.png');
png(padded('#ffffff'), 32, 'favicon-dark-32x32.png');
png(squared('#ffffff', '#000000'), 180, 'apple-touch-icon.png');
png(squared('#ffffff', '#000000'), 192, 'logo192.png');
png(squared('#ffffff', '#000000'), 512, 'logo512.png');

// ---- React component that replaces packages/webapp/src/assets/LogoInverted.tsx ----
// Uses currentColor so it follows the dashboard light/dark theme, like the original.
const tsx = `// Generated by branding/scripts/generate.mjs - do not edit by hand.
import React from 'react';

export const LogoInverted = ({ className, ...props }: React.SVGProps<SVGSVGElement>) => {
    return (
        <svg width="114" height="117" viewBox="${viewBox}" fill="currentColor" xmlns="http://www.w3.org/2000/svg" className={className} {...props}>
            <path fill="currentColor" d="${pathD}" />
        </svg>
    );
};
`;
mkdirSync(join(out, 'webapp-src'), { recursive: true });
writeFileSync(join(out, 'webapp-src', 'LogoInverted.tsx'), tsx);

console.log('branding/generated generated');
